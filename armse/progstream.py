"""python3 -m armse.progstream [outdir] -> results/PROGRAM_STREAMING.md   (MODEL ONLY)
Descriptor streaming: every `blk` DMA entries the DMA engine first fetches the next block of descriptors
(blk DMA entries + proportional compute entries, 16 B each) as one burst over the same bus. Compute
descriptors are assumed prefetched with them (optimistic). Schedules are held fixed; only the cost is added."""
import sys
import pandas as pd
from .config import HwConfig
from .workloads import suite
from .scheduler import policy_C, policy_D_fb
from .schedule import build_program
from .sim import simulate
from .bench import md, gm


def main(out="results"):
    hw0, rows = HwConfig(), []
    for wl in suite():
        for name, fn in (("C_fixed_double", policy_C), ("D_feedback", policy_D_fb)):
            s = fn(wl, hw0)
            base = simulate(build_program(wl, hw0, s)).cycles
            for blk in (4, 8, 16, 32):
                hw = hw0.replace(prog_fetch_block=blk)
                c = simulate(build_program(wl, hw, s)).cycles
                rows.append(dict(workload=wl.name, policy=name, block=blk, base_cycles=base, stream_cycles=c, slowdown=c / base))
        print(wl.name, flush=True)
    df = pd.DataFrame(rows)
    df.to_csv(f"{out}/program_streaming.csv", index=False)
    g = df.groupby(["policy", "block"]).slowdown.agg(geomean=gm, median="median", worst="max").reset_index()
    piv = df.pivot_table(index=["workload", "block"], columns="policy", values="stream_cycles").reset_index()
    piv["D_over_C"] = piv.D_feedback / piv.C_fixed_double
    d = piv.groupby("block").D_over_C.apply(gm).reset_index().rename(columns={"D_over_C": "geomean D_feedback / C_fixed_double (both streaming)"})
    rep = ["# Descriptor streaming cost (MODEL ONLY, generated by `python3 -m armse.progstream`)\n",
           "Slowdown = cycles with streamed descriptors / cycles with an on-chip program (schedules unchanged).\n",
           md(g, "{:.4f}"), "\n## Does the adaptive advantage survive the streaming cost?\n", md(d, "{:.3f}")]
    open(f"{out}/PROGRAM_STREAMING.md", "w").write("\n".join(rep))
    print(g.to_string()); print(d.to_string())


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "results")
