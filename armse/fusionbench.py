"""Fusion study:  python3 -m armse.fusionbench [outdir]  ->  results/fusion.csv, results/FUSION_REPORT.md
MODEL ONLY. Conservative: phases/blocks are separate programs with barriers; requant cost included."""
import sys
import time
import pandas as pd
from .config import HwConfig, NoFitError
from .fused import chains, run_unfused, best_fused, chain_data, chain_reference, run_fused
from .bench import md, gm
import numpy as np


def main(out="results"):
    t0 = time.time()
    rows, ver_ok, ver_n = [], 0, 0
    for depth in (256, 1024, 4096):
        hw = HwConfig(a_depth=depth)
        for ch in chains():
            if depth == 1024 and not ch.name.startswith(("attn_s128", "mlp_b32", "mlp_b64", "wideN1")):
                continue
            u = run_unfused(ch, hw)
            row = dict(chain=ch.name, a_buf_bytes=hw.lanes * depth, M=ch.M, K1=ch.K1, N1=ch.N1, N2=ch.N2,
                       unfused_cycles=u["cycles"], unfused_bytes=u["bytes_rd"] + u["bytes_wr"])
            try:
                f = best_fused(ch, hw)
                data = chain_data(ch, 1)
                fv = run_fused(ch, hw, f["tm"], data)
                ver_n += 1
                ver_ok += int((fv["C2"] == chain_reference(*data, ch.shift)).all())
                row.update(fused_cycles=f["cycles"], fused_bytes=f["bytes_rd"] + f["bytes_wr"], tm=f["tm"],
                           blocks=f["nblocks"], cycles_ratio=f["cycles"] / u["cycles"],
                           bytes_ratio=(f["bytes_rd"] + f["bytes_wr"]) / (u["bytes_rd"] + u["bytes_wr"]),
                           inter_written_unfused=ch.M * ch.N1, status="fits")
            except NoFitError:
                row.update(status="no fit (intermediate block > A buffer)")
            rows.append(row)
            print(depth, ch.name, row.get("cycles_ratio"), f"{time.time() - t0:.0f}s", flush=True)
    df = pd.DataFrame(rows)
    df.to_csv(f"{out}/fusion.csv", index=False)
    fit = df[df.status == "fits"]
    rep = ["# Fused GEMM chains (model only, generated by `python3 -m armse.fusionbench`)\n",
           "Fused = row blocks of `tm` rows; the requantised INT8 intermediate (tm x N1) lives in the A buffer; B1/B2 are "
           "re-streamed per block. Unfused = two independent D_feedback programs. Cycle ratio < 1 means fusion is faster. "
           "Barriers between phases/blocks and per-tile requantisation cost are included, which penalises fusion "
           f"(conservative). Functional check: {ver_ok}/{ver_n} fused configurations bit-exact vs an independent numpy "
           "reference (including requantisation).\n",
           md(df[["chain", "a_buf_bytes", "M", "K1", "N1", "N2", "unfused_cycles", "fused_cycles", "cycles_ratio",
                  "unfused_bytes", "fused_bytes", "bytes_ratio", "tm", "blocks", "status"]].fillna("-"))]
    if len(fit):
        rep.append(f"\nGeomean over configurations that fit: cycles ratio {gm(fit.cycles_ratio):.3f}, bytes ratio "
                   f"{gm(fit.bytes_ratio):.3f}; fusion faster in {(fit.cycles_ratio < 1).sum()}/{len(fit)} cases, "
                   f"lower traffic in {(fit.bytes_ratio < 1).sum()}/{len(fit)}.\n")
    with open(f"{out}/FUSION_REPORT.md", "w") as fh:
        fh.write("\n".join(rep))
    print("done", f"{time.time() - t0:.0f}s")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "results")
