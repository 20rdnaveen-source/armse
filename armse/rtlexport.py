"""Descriptor packing + RTL golden-vector export.  Single source of truth for the field layout:
rtl/armse_fields.vh is GENERATED from FIELDS below (run `python3 -m armse.rtlexport`)."""
import os
import sys
import numpy as np
from .config import HwConfig, Workload, ScheduleError
from .schedule import Schedule, build_program, LA, LB, WB
from .sim import simulate, reference, random_operands

DMA_FIELDS = [("TYPE", 2), ("DEP", 20), ("ROWS", 8), ("COLS", 8), ("EXT_ADDR", 32),
              ("EXT_STRIDE", 16), ("BASE", 16), ("STRIDE", 8)]
CMP_FIELDS = [("TM", 8), ("TN", 8), ("TK", 8), ("FIRST", 1), ("DEP", 20),
              ("ABASE", 16), ("BBASE", 16), ("OBASE", 16)]
WORD_BITS = 128
CNT_BITS = 20


def layout(fields):
    pos, out = 0, {}
    for name, w in fields:
        out[name] = (pos, w)
        pos += w
    assert pos <= WORD_BITS
    return out


DMA_L, CMP_L = layout(DMA_FIELDS), layout(CMP_FIELDS)


def pack(lay, values):
    word = 0
    for name, (lo, w) in lay.items():
        v = int(values[name])
        if v < 0 or v >= (1 << w):
            raise ScheduleError(f"descriptor field {name}={v} does not fit in {w} bits")
        word |= v << lo
    return word


def unpack(lay, word):
    return {n: (word >> lo) & ((1 << w) - 1) for n, (lo, w) in lay.items()}


def pack_dma(op):
    return pack(DMA_L, dict(TYPE=op.kind, DEP=op.dep_cp, ROWS=op.rows, COLS=op.cols,
                            EXT_ADDR=op.ext_addr, EXT_STRIDE=op.ext_stride, BASE=op.base, STRIDE=op.stride))


def pack_cmp(op):
    return pack(CMP_L, dict(TM=op.tm, TN=op.tn, TK=op.tk, FIRST=int(op.first), DEP=op.dep_dma,
                            ABASE=op.a_base, BBASE=op.b_base, OBASE=op.o_base))


def fields_vh():
    lines = ["// GENERATED by armse/rtlexport.py - do not edit.", f"`define CNT_W {CNT_BITS}"]
    for pre, lay in (("DMA", DMA_L), ("CMP", CMP_L)):
        for n, (lo, w) in lay.items():
            lines.append(f"`define {pre}_{n}_LO {lo}")
            lines.append(f"`define {pre}_{n}_HI {lo + w - 1}")
    lines += ["`define T_LA 2'd0", "`define T_LB 2'd1", "`define T_WB 2'd2"]
    return "\n".join(lines) + "\n"


# Hardware configuration the RTL testbenches are generated for (must match tb parameters).
def rtl_hw(lanes=8):
    return HwConfig(lanes=lanes, bus_bytes=4, row_lat=3, a_depth=64, b_depth=64, o_words=256)


RTL_CASES = [
    # name, (M,N,K), lanes, Schedule
    ("t01_basic16", (16, 16, 16), 8, Schedule(16, 16, 16, "MN", 1, 1)),
    ("t02_ragged_db", (13, 11, 19), 8, Schedule(8, 8, 8, "NM", 2, 2)),
    ("t03_oddtiles", (20, 17, 33), 8, Schedule(7, 5, 9, "MN", 2, 1)),
    ("t04_gemv", (1, 9, 40), 8, Schedule(1, 9, 20, "MN", 2, 2)),
    ("t05_lanes4", (12, 10, 14), 4, Schedule(6, 5, 7, "MN", 2, 2)),
    ("t06_retain", (24, 24, 16), 8, Schedule(8, 8, 16, "MN", 2, 1)),
    ("t07_kloop_single", (9, 9, 40), 8, Schedule(9, 9, 10, "NM", 1, 1)),
]


def export_case(outdir, name, dims, lanes, sch, seed=0):
    hw = rtl_hw(lanes)
    wl = Workload(name, *dims)
    prog = build_program(wl, hw, sch)
    A, B = random_operands(wl, seed)
    res = simulate(prog, A, B, functional=True)
    ref = reference(A, B)
    assert (res.C == ref).all(), "model disagrees with reference - refusing to export"
    d = os.path.join(outdir, name)
    os.makedirs(d, exist_ok=True)
    lay = prog.layout
    ext = bytearray(lay.ext_bytes)
    ext[lay.a_off:lay.a_off + A.size] = A.astype(np.int8).tobytes()
    ext[lay.b_off:lay.b_off + B.size] = B.astype(np.int8).tobytes()
    with open(os.path.join(d, "ext.hex"), "w") as f:
        f.write("\n".join(f"{b:02x}" for b in ext) + "\n")
    with open(os.path.join(d, "dprog.hex"), "w") as f:
        f.write("\n".join(f"{pack_dma(o):032x}" for o in prog.dma) + "\n")
    with open(os.path.join(d, "cprog.hex"), "w") as f:
        f.write("\n".join(f"{pack_cmp(o):032x}" for o in prog.cmp) + "\n")
    with open(os.path.join(d, "expc.hex"), "w") as f:
        f.write("\n".join(f"{int(v) & 0xFFFFFFFF:08x}" for v in ref.flatten()) + "\n")
    m = res.metrics
    kg = -(-sch.tk // lanes)
    meta = [f"`define NB_P {lanes}", f"`define LOGNB_P {lanes.bit_length() - 1}",
            f"`define A_DEPTH_P {hw.a_depth}", f"`define B_DEPTH_P {hw.b_depth}",
            f"`define O_DEPTH_P {hw.o_words}", f"`define ROW_LAT_P {hw.row_lat}",
            f"`define N_DMA {len(prog.dma)}", f"`define N_CMP {len(prog.cmp)}",
            f"`define EXT_BYTES {lay.ext_bytes}", f"`define C_OFF {lay.c_off}",
            f"`define C_WORDS {wl.M * wl.N}", f"`define EXP_BYTES_RD {m['bytes_rd']}",
            f"`define EXP_BYTES_WR {m['bytes_wr']}", f"`define EXP_XFER {m['transfers']}",
            f"`define EXP_CYCLES {m['cycles']}", f"`define EXP_CMP_BUSY {m['compute_busy'] - len(prog.cmp)}",
            f"`define EXP_DMA_BUSY {m['dma_busy'] - len(prog.dma)}", f'`define TEST_NAME "{name}"']
    with open(os.path.join(d, "meta.vh"), "w") as f:
        f.write("\n".join(meta) + "\n")
    return m


def main(root="."):
    with open(os.path.join(root, "rtl", "armse_fields.vh"), "w") as f:
        f.write(fields_vh())
    out = os.path.join(root, "rtl_vectors")
    summary = []
    for name, dims, lanes, sch in RTL_CASES:
        m = export_case(out, name, dims, lanes, sch)
        summary.append((name, m["cycles"], m["bytes_rd"], m["bytes_wr"], m["transfers"]))
    with open(os.path.join(out, "SUMMARY.txt"), "w") as f:
        f.write("name cycles bytes_rd bytes_wr transfers\n")
        for r in summary:
            f.write(" ".join(str(x) for x in r) + "\n")
    return summary


if __name__ == "__main__":
    for r in main(sys.argv[1] if len(sys.argv) > 1 else "."):
        print(r)
